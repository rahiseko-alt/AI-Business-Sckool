def hm(hhmm, m):
    return (dt.datetime.strptime(hhmm, "%H:%M") + dt.timedelta(minutes=m)).strftime("%H:%M")


def jdate(iso):
    d = dt.date.fromisoformat(iso)
    return f"{d.year}年{d.month}月{d.day}日（{WD[d.weekday()]}）"


