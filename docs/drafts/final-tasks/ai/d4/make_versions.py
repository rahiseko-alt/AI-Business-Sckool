def compute(v, rows, ge=False, use_ext=True, reset=True, limit_h=None):
    p = VERSIONS[v]
    H = p["H"] if limit_h is None else limit_h
    ev = {i: [] for i in IDS}
    for d, s, r, st, k, ext in sorted(rows, key=lambda x: (x[0], x[3])):
        if reset and not d.startswith("2026-10"):
            continue
        m = minutes(v, k)
        lim = H + (p["E"] if (use_ext and ext == "あり") else 0)
        if m > lim or (ge and m == lim):
            ev[sid_of(v, s)].append(d)
    res = {}
    for i in IDS:
        n = len(ev[i])
        res[i] = (n, (dt.date.fromisoformat(ev[i][2]) + dt.timedelta(days=1)).isoformat() if n >= 3 else "")
    return res


def room_counts(v, rows, only_oct=True):
    c = {i: 0 for i in range(1, VERSIONS[v]["R"] + 1)}
    for d, s, r, st, k, ext in rows:
        if only_oct and not d.startswith("2026-10"):
            continue
        c[room_of(v, r)] += 1
    return c


def verify_csv(v, paths):
    p = VERSIONS[v]
    ev, rooms = [], {i: 0 for i in range(1, p["R"] + 1)}
    for path in paths:
        with open(path, encoding="utf-8") as f:
            for r in csv.DictReader(f):
                a = dt.datetime.fromisoformat(f"{r['日付']}T{r['入室']}")
                b = dt.datetime.fromisoformat(f"{r['日付']}T{r['退室']}")
                assert a.weekday() < 5 and r["退室"] <= "18:00" and r["日付"] != "2026-10-12"
                if (a.year, a.month) != (2026, 10):
                    continue
                rooms[int(r["部屋"][3:])] += 1
                if b > a + dt.timedelta(minutes=p["H"] + (p["E"] if r["延長"] == "あり" else 0)):
                    ev.append((b, r["学籍番号"]))
    ev.sort()
    res = {}
    for i in IDS:
        ds = [b.date() for b, s in ev if s == i]
        res[i] = (len(ds), (ds[2] + dt.timedelta(days=1)).isoformat() if len(ds) >= 3 else "")
    return res, rooms


