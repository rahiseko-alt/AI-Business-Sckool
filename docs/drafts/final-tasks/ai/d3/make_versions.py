         "| E4 | 2人以上で使ってください（1人では使えません） | 1人でも使える | 第3条 | 条件 |",
         f"| E5 | 1回{OLD_H}分まで | 版の上限（下の表） | 第5条 | **旧版の値**（改定の記録） |",
         "| E6 | 三脚は事務室で借りられます | 各自で持ってくる。貸し出さない | 第8条 | **旧版の値** |",
