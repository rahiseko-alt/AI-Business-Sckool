def sid_of(v, s):
    return PERM[v][IDS.index(s)]


def minutes(v, kind):
    p = VERSIONS[v]
    t, d = kind
    return {"abs": d, "h": p["H"] + d, "he": p["H"] + p["E"] + d}[t]


def hm(hhmm, m):
    return (dt.datetime.strptime(hhmm, "%H:%M") + dt.timedelta(minutes=m)).strftime("%H:%M")


def rows_for(v, rows):
    out = []
    for d, s, room, st, kind, ext in rows:
        room = (room - 1) % VERSIONS[v]["R"] + 1
        out.append([d, sid_of(v, s), f"No.{room}", st, hm(st, minutes(v, kind)), ext])
    return out


def rule(v):
    p = VERSIONS[v]
    return f"""## 材料A ルールの原文（これだけが正しい）

### つばさ国際ビジネス学院（架空） 面接練習室利用規程

2026年4月1日改定

**第1条（目的）** 就職の面接を練習する学生のために、面接練習室の使い方を定める。

**第2条（部屋）** 面接練習室は2階に{p['R']}室（No.1〜No.{p['R']}）ある。

**第3条（使える人）** 在籍する学生が使える。1人でも使える。

**第4条（使える日と時間）** 平日の9時00分から18時00分まで使える。土曜日・日曜日・祝日は使えない。

**第5条（1回の上限）** 1回に使える時間は、入室した時刻から{p['H']}分までとする。

**第6条（延長）** 次の予約が入っていない場合に限り、1回の利用につき1回だけ、{p['E']}分延長できる。延長するときは、上限の時刻より前に事務室に申し出る。

**第7条（予約）** 予約は、使う日の前日の17時00分までに、学院の予約フォームで行う。

**第8条（備品）** スーツ用のハンガーと鏡は部屋に置いてある。録画用の三脚は各自で持ってくる。学院は三脚を貸し出さない。

**第9条（飲食）** 飲み物・食べ物は持ち込めない。

**第10条（違反）** 上限の時刻を過ぎて退室した場合、違反1回とする。延長を認められた利用では、延長した後の時刻を上限とする。退室した時刻が上限の時刻ちょうどのときは、違反としない。

**第11条（予約の停止）** 違反が3回になった人は、3回目の違反の翌日から{p['S']}日間、予約できない。

**第12条（問い合わせ）** わからないことは、事務室で聞く。

#### 改定の記録

- 2026年4月1日: 1回の上限を{OLD_H}分から{p['H']}分に変更した。三脚の貸出しをやめた。
- 2025年4月1日: 制定（1回の上限は{OLD_H}分、三脚は事務室で貸出し）。
"""


def draft(v):
    p = VERSIONS[v]
    body = f"""## 面接練習室で、本番に強くなろう！

面接の練習に、2階の面接練習室を使えます。部屋は**6室**あります。

### 使える人と時間
- **2人以上で使ってください**（1人では使えません）
- 平日の 9:00〜18:00（土日・祝日は使えません）
- 1回**{OLD_H}分まで**使えます
- 延長したいときは、事務室に言えば**何回でも**延長できます

### 予約のしかた
- 使う日の**当日の朝9時まで**に、予約フォームで予約してください

### 持ち物
- スーツ用のハンガーと鏡は部屋にあります
- 録画用の三脚は**事務室で借りられます**
- ペットボトルの飲み物なら持ち込めます

### 守ってほしいこと
- 上限の時刻を過ぎて退室すると、違反1回です
- 違反が3回になると、翌日から**{p['S']}日間**予約できません

わからないことは、事務室まで。
"""
    for right, wrong in p["typos"]:
        assert body.count(right) == 1, (v, right)
        body = body.replace(right, wrong)
    return body


