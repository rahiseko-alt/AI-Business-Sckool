def compute(v, rows, limit_h=None, use_ext=True, ge=False):
    """正解（と、よくある間違い）を型から計算する。"""
    p = VERSIONS[v]
    H = p["H"] if limit_h is None else limit_h
    viol = {i: [] for i in IDS}
    for d, s, _, _, kind, ext in sorted(rows, key=lambda r: (r[0], r[3])):
        m = minutes(v, kind)
        lim = H + (p["E"] if (use_ext and ext == "あり") else 0)
        if m > lim or (ge and m == lim):
            viol[sid_of(v, s)].append(d)
    res = {}
    for i in IDS:
        n = len(viol[i])
        stop = ""
        if n >= 3:
            stop = (dt.date.fromisoformat(viol[i][2]) + dt.timedelta(days=1)).isoformat()
        res[i] = (n, stop)
    return res


def verify_from_csv(v, paths):
    """配った CSV（と隠しテスト）だけから、日時の計算で数え直す。"""
    p = VERSIONS[v]
    ev = []
    for path in paths:
        with open(path, encoding="utf-8") as f:
            for r in csv.DictReader(f):
                a = dt.datetime.fromisoformat(f"{r['日付']}T{r['入室']}")
                b = dt.datetime.fromisoformat(f"{r['日付']}T{r['退室']}")
                assert a.weekday() < 5 and r["日付"] != "2026-10-12" and r["退室"] <= "18:00"
                lim = a + dt.timedelta(minutes=p["H"] + (p["E"] if r["延長"] == "あり" else 0))
                if b > lim:
                    ev.append((b, r["学籍番号"]))
    ev.sort()
    res = {}
    for i in IDS:
        ds = [b.date() for b, s in ev if s == i]
        res[i] = (len(ds), (ds[2] + dt.timedelta(days=1)).isoformat() if len(ds) >= 3 else "")
    return res


