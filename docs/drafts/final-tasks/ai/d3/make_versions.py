         "| 記号 | 下書きの文 | 正しい内容 | 原文 | 罠の種類 |", "| --- | --- | --- | --- | --- |",
         "| E1 | 部屋は6室 | 版の部屋数（下の表） | 第2条 | 数字（版で変わる） |",
