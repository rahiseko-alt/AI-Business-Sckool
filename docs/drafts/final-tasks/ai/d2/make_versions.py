"""成果物2（グループ学習室）の版0〜4を作り、正解を別の計算で検算する。

使い方: python3 make_versions.py
  -> student-material-v0.md 〜 v4.md、student-log-v0.csv 〜 v4.csv（学生。v0 は練習版）
     teacher-key.md（教員だけ）
"""
import csv
import datetime as dt
import os

OUT = os.path.dirname(os.path.abspath(__file__))

# C=定員、H=1回の上限（分）、D=何日前から予約できるか、typos=(正しい語, 誤字) を2つ（1つ目は読めない字、2つ目は実在する語）
VERSIONS = {
    0: dict(C=4, H=60, D=3, typos=[("予約のしかた", "予訳のしかた"), ("図書室の奥", "図書室の沖")]),
    1: dict(C=6, H=90, D=7, typos=[("入室した", "入質した"), ("退室すると", "体質すると")]),
    2: dict(C=5, H=100, D=14, typos=[("違反1回", "遺反1回"), ("予約フォームで", "予約ホームで")]),
    3: dict(C=8, H=80, D=5, typos=[("予約のしかた", "予訳のしかた"), ("使えるのは", "仕えるのは")]),
    4: dict(C=4, H=70, D=10, typos=[("図書室の奥", "図書質の奥"), ("退室すると", "体質すると")]),
}

# (日付, 代表者, 部屋, 入室, 上限との差（分）)。差>0 が違反、差=0 は上限ちょうど（違反でない）
ROWS = [
    ("2026-10-05", "G01", "A室", "09:00", +10),
    ("2026-10-05", "G02", "B室", "13:00", 0),
    ("2026-10-06", "G03", "A室", "10:00", +1),
    ("2026-10-07", "G04", "C室", "09:30", -20),
    ("2026-10-08", "G01", "B室", "14:00", +25),
    ("2026-10-09", "G05", "A室", "10:30", -30),
    ("2026-10-13", "G06", "C室", "13:30", +30),
    ("2026-10-14", "G02", "A室", "09:00", -5),
    ("2026-10-15", "G03", "B室", "15:00", 0),
    ("2026-10-16", "G04", "A室", "11:00", +15),
    ("2026-10-19", "G01", "C室", "09:00", -10),
    ("2026-10-20", "G06", "B室", "14:30", -1),
]
IDS = ["G01", "G02", "G03", "G04", "G05", "G06"]
# 版ごとに代表者の番号を入れ替える（隣の版と答えが同じにならないように）
PERM = {
    0: ["G02", "G05", "G01", "G06", "G03", "G04"],
    1: ["G01", "G02", "G03", "G04", "G05", "G06"],
    2: ["G03", "G06", "G04", "G05", "G01", "G02"],
    3: ["G05", "G04", "G06", "G01", "G02", "G03"],
    4: ["G06", "G03", "G02", "G05", "G04", "G01"],
}


def sid_of(v, sid):
    return PERM[v][IDS.index(sid)]


def add_min(hhmm, m):
    return (dt.datetime.strptime(hhmm, "%H:%M") + dt.timedelta(minutes=m)).strftime("%H:%M")


def rule(v):
    p = VERSIONS[v]
    return f"""## 材料A ルールの原文（これだけが正しい）

### つばさ国際ビジネス学院（架空） グループ学習室利用規程

**第1条（目的）** グループで課題に取り組む学生のために、グループ学習室の使い方を定める。

**第2条（部屋と定員）** グループ学習室は図書室の奥に3室（A室・B室・C室）ある。1室の定員は{p['C']}人とする。

**第3条（使える人）** 在籍する学生が、2人以上のグループで使う。1人では使えない。

**第4条（使える日と時間）** 平日の9時00分から18時00分まで使える。土曜日・日曜日・祝日は使えない。

**第5条（1回の上限）** 1回に使える時間は、入室した時刻から{p['H']}分までとする。

**第6条（予約）** 予約は、使う日の{p['D']}日前から、前日の17時00分まで、学院の予約フォームで行う。当日の予約は受け付けない。

**第7条（取消し）** 予約を取り消すときは、使う日の前日の17時00分までに、予約フォームで取り消す。

**第8条（違反）** 上限の時刻を過ぎて退室した場合、違反1回とする。退室した時刻が上限の時刻ちょうどのときは、違反としない。
"""


def draft(v):
    p = VERSIONS[v]
    body = f"""## グループ学習室を使ってみよう！

友だちと課題に取り組むなら、グループ学習室が便利です。
図書室の奥に3室あり、1室**10人まで**使えます。

### 使える人・日・時間
- **1人でも使えます**
- 平日の 9:00〜18:00（土日・祝日は使えません）
- 1回に使えるのは、入室した時刻から**{p['H']}分まで**です

### 予約のしかた
- 使う日の**30日前から**、前日の17:00まで、予約フォームで予約してください
- **当日でも、空いていれば予約できます**

### 守ってほしいこと
- 上限の時刻を過ぎて退室すると、違反1回になります
"""
    for right, wrong in p["typos"]:
        assert body.count(right) == 1, (v, right)
        body = body.replace(right, wrong)
    return body


SLIDE_CARD = """## 材料D スライドの条件カード

依頼: 新入生に、グループ学習室の使い方を説明するスライドを作る。**材料A（原文）の内容で**作る。

| 番号 | タイトル | 必ず入れる中身 |
| --- | --- | --- |
| 01 | 予約のしかた | 予約できる期間（何日前から、いつまで）／当日は予約できないこと／取消しの締切 |
| 02 | 使い方 | 使える人数（2人以上、定員）／1回の上限／上限の時刻ちょうどに退室するのは違反にならないこと |

形の約束:
1. スライドは**ちょうど2枚**（表紙は作らない）
2. すべてのスライドの**右下**に 01・02 の番号を入れる
3. 括弧は**（）の1種類だけ**。「」『』【】［］は1つも使わない
"""

IMAGE_CARD = """## 材料E 画像の条件カード

配られた画像（ゴシック調のイラスト）を、**リアル調（写真のような見た目）**に変えてください。
**同じ条件で3枚**作り、3枚とも提出します（3枚とも条件を満たすかを見ます）。

| 番号 | 条件 |
| --- | --- |
| 1 | リアル調（写真のよう）にする。とがったアーチの窓・ろうそくなど、ゴシック調の飾りを残さない |
| 2 | 椅子は**4脚**のまま |
| 3 | 机の上の本は**緑**で**2冊**のまま |
| 4 | ホワイトボードは**左の壁**のまま |
| 5 | 横長 16:9 のまま |

人の顔、実在の会社・製品のロゴは入れない。
"""


def log_rows(v):
    H = VERSIONS[v]["H"]
    return [[d, sid_of(v, s), room, st, add_min(st, H + diff)] for d, s, room, st, diff in ROWS]


def key_counts(v, ge=False):
    c = {i: 0 for i in IDS}
    for _, s, _, _, diff in ROWS:
        if diff > 0 or (ge and diff == 0):
            c[sid_of(v, s)] += 1
    return c


def verify():
    for v in VERSIONS:
        H = VERSIONS[v]["H"]
        c = {i: 0 for i in IDS}
        with open(os.path.join(OUT, f"student-log-v{v}.csv"), encoding="utf-8") as f:
            for r in csv.DictReader(f):
                a = dt.datetime.fromisoformat(f"{r['日付']}T{r['入室']}")
                b = dt.datetime.fromisoformat(f"{r['日付']}T{r['退室']}")
                assert a.weekday() < 5 and r["退室"] <= "18:00" and r["日付"] != "2026-10-12"
                if b > a + dt.timedelta(minutes=H):
                    c[r["代表者"]] += 1
        assert c == key_counts(v), (v, c)
    print("verify OK: 版0〜4 の違反回数が一致")


def main():
    for v in VERSIONS:
        with open(os.path.join(OUT, f"student-log-v{v}.csv"), "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f, lineterminator="\n")
            w.writerow(["日付", "代表者", "部屋", "入室", "退室"])
            w.writerows(log_rows(v))
        label = "練習版" if v == 0 else f"版{v}"
        md = f"""# 成果物2 材料（{label}）

配り方: このファイルを Google ドキュメントにして「コピーを作成」リンクで配る。材料C は `student-log-v{v}.csv` をスプレッドシートにして「コピーを作成」リンクで配る。
学校名・学籍番号はすべて架空。

{rule(v)}
---

## 材料B 張り紙の下書き（事務室の先輩が AI で作った。原文と照らし合わせていない）

{draft(v)}
---

## 材料C 利用記録（スプレッドシートで配る）

10月の利用記録12行。列は 日付・代表者（学籍番号）・部屋・入室・退室。

---

{SLIDE_CARD}
---

{IMAGE_CARD}"""
        with open(os.path.join(OUT, f"student-material-v{v}.md"), "w", encoding="utf-8") as f:
            f.write(md)
    verify()

    L = ["# 成果物2 正解表（教員だけ。学生に渡さない）", "",
         "`make_versions.py` で作り、配った CSV から別の書き方で数え直して一致を確かめた。", "",
         "## 1. 張り紙の下書きの誤り（6件。学生には数を知らせない）", "",
         "| 記号 | 下書きの文 | 正しい内容 | 原文 |", "| --- | --- | --- | --- |",
         "| E1 | 1室10人まで | 版の定員（下の表） | 第2条 |",
         "| E2 | 30日前から | 版の日数（下の表）の日前から | 第6条 |",
         "| E3 | 1人でも使えます | 2人以上のグループで使う。1人では使えない | 第3条 |",
         "| E4 | 当日でも、空いていれば予約できます | 当日の予約は受け付けない | 第6条 |",
         "| T1・T2 | 版ごとの誤字2つ（下の表） | 正しい語 | 誤字 |", "",
         "誤りでない文: 図書室の奥に3室／平日の9:00〜18:00（土日・祝日は不可）／版の上限の分数（下書きは正しい）／前日の17:00まで／上限を過ぎて退室すると違反1回。", "",
         "| 版 | 定員（E1） | 予約開始（E2） | 上限（分） | 誤字 T1（読めない字） | 誤字 T2（実在する語） |",
         "| --- | --- | --- | --- | --- | --- |"]
    for v, p in VERSIONS.items():
        (r1, w1), (r2, w2) = p["typos"]
        L.append(f"| {v if v else '0（練習）'} | {p['C']}人 | {p['D']}日前 | {p['H']} | {w1}→{r1} | {w2}→{r2} |")
    L += ["", "## 2. 集計表「結果」の正解（B2〜B7 は式であること）", "",
          "| 版 | " + " | ".join(IDS) + " |", "| --- | " + " | ".join(["---"] * 6) + " |"]
    for v in VERSIONS:
        L.append(f"| {v if v else '0（練習）'} | " + " | ".join(str(key_counts(v)[i]) for i in IDS) + " |")
    L += ["", "よくある間違い（上限ちょうどを違反にする `>=`）の結果:", "",
          "| 版 | " + " | ".join(IDS) + " |", "| --- | " + " | ".join(["---"] * 6) + " |"]
    for v in VERSIONS:
        L.append(f"| {v if v else '0（練習）'} | " + " | ".join(str(key_counts(v, ge=True)[i]) for i in IDS) + " |")
    L += ["", "上限ちょうどの行が2行、1分だけ超えた行が1行ある（どの代表者になるかは版で違う）。",
          "", "## 3. スライド（2枚）", "",
          "| 番号 | ○に必要な中身 | 1つでもあれば✖ |", "| --- | --- | --- |",
          "| 01 | 版の日数の日前から／前日17時まで／当日は不可／取消しは前日17時まで | 30日前、当日可 |",
          "| 02 | 2人以上／版の定員／版の上限（分）／ちょうどは違反でない | 1人でも可、10人 |",
          "", "## 4. 画像（3枚とも）", "",
          "| 条件 | 見る所 |", "| --- | --- |",
          "| 1 リアル調 | 写真のよう。アーチの窓・ろうそくがない |",
          "| 2 椅子4脚 | ちょうど4脚 |",
          "| 3 緑の本2冊 | 机の上の本がちょうど2冊で、2冊とも緑 |",
          "| 4 ホワイトボードは左 | 画面の左側の壁にある |",
          "| 5 16:9 | 横÷縦が1.7〜1.8 |", ""]
    with open(os.path.join(OUT, "teacher-key.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))


if __name__ == "__main__":
    main()
