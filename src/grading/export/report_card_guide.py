"""前期の成績表（Excel）の先頭に「使い方」シートを足す。AI を使わずに成績を直す手順を、素人向けに書く。

式は使わない（文字だけ）。開いたときに最初に出るシートにする。
"""

from openpyxl.styles import Alignment, Font, PatternFill

GUIDE_SHEET = "使い方"
# 手順の中で名前を出すシート（作るシートと名前がずれないように、テストで確かめる）
SHEETS_NAMED = ("AI計算版_国際", "AI計算版_総合", "例外", "特記事項", "確認",
                "通知表_1人", "成績証明書_1人", "通知表_全員")

STEPS = [
    ("はじめに", [
        "このファイルが前期の成績の正本です。直すときは、まず別名で保存して控えを残してください。",
        "数字を直接打ってあるマスだけを直します。合計・評定・通知表は自動で書き換わります。",
        "「=」で始まる式のマスは触りません（マスを選ぶと、上の入力欄に「=…」と出るのが式です）。",
    ]),
    ("1. 点数がまちがっていたとき", [
        "「AI計算版_国際」または「AI計算版_総合」を開きます。",
        "その学生の行と、科目・評価項目（授業態度・テストなど）の列が交わるマスの数字を直します。",
        "テストの点を満点に換算している科目は、換算前の元の点が入ったマス（式ではない方）を直します。",
    ]),
    ("2. 出席がまちがっていたとき", [
        "「国際ビジネスAI科 〇月」「総合ビジネス科 〇月」のシートで、その日の欠・遅のマスを直します。",
        "出席の点と通知表の出席時数は、自動で計算し直されます。",
    ]),
    ("3. 特別な扱いをするとき（例: その科目だけ F と表示する）", [
        "「例外」シートに1行足します: A 学籍番号、B 科目（通知表に出る科目名のとおり）、C 表示する評定、D 理由。",
        "G 列に「反映済み」と出れば効いています。出なければ学籍番号か科目名の書き方が違います。",
    ]),
    ("4. 備考を書くとき", [
        "「特記事項」シートの、その学生の行の B 列に書きます。通知表の特記事項欄に出ます。",
    ]),
    ("5. 点検（必ず行う）", [
        "「確認」シートの B2 が 0 なら問題ありません。",
        "0 でなければ、下に出ている学生・科目を見て、1〜4 の手順で直します。赤いマスも要確認です。",
    ]),
    ("6. 印刷", [
        "1人分: 「通知表_1人」の黄色のマス（B1）に学籍番号を入れて印刷します。",
        "成績証明書: 「成績証明書_1人」の黄色のマス（B1）に学籍番号を入れて印刷します。",
        "全員分: 「通知表_全員」を印刷します（1人1ページ）。",
        "初めて印刷するときは、印刷プレビューで1人が1ページに収まっているかを見てください。",
    ]),
    ("7. 保存", [
        "最後に上書き保存します。",
    ]),
]


def add_guide(wb):
    ws = wb.create_sheet(GUIDE_SHEET, 0)
    ws.column_dimensions["A"].width = 4
    ws.column_dimensions["B"].width = 110
    ws["A1"] = "前期の成績表の使い方（成績を直すとき）"
    ws["A1"].font = Font(bold=True, size=14)
    head_fill = PatternFill("solid", fgColor="DDEBF7")
    wrap = Alignment(wrap_text=True, vertical="top")
    r = 3
    for title, lines in STEPS:
        ws.cell(r, 1, title).font = Font(bold=True, size=12)
        for col in (1, 2):
            ws.cell(r, col).fill = head_fill
        r += 1
        for line in lines:
            ws.cell(r, 1, "・")
            ws.cell(r, 2, line).alignment = wrap
            r += 1
        r += 1
    ws.sheet_view.showGridLines = False
    wb.active = 0
    for other in wb.worksheets[1:]:
        other.sheet_view.tabSelected = False
    return ws
